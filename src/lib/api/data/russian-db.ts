/**
 * Fast O(1) in-memory lookup for Russian anime title by any ID or normalized key.
 */
export function lookupRussianAnimeTitle(key: string | number): string | null {
  if (!key) return null;
  const str = String(key).toLowerCase().trim();
  if (RUSSIAN_ANIME_DB[str]) return RUSSIAN_ANIME_DB[str];

  const slug = str.replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
  if (RUSSIAN_ANIME_DB[slug]) return RUSSIAN_ANIME_DB[slug];

  // Match sub-keys
  if (slug.length > 4) {
    for (const [k, v] of Object.entries(RUSSIAN_ANIME_DB)) {
      if (k.length > 5 && (slug.includes(k) || k.includes(slug))) {
        return v;
      }
    }
  }

  return null;
}
