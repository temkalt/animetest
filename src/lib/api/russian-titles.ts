export function generateRussianGenreSynopsis(
  title: string,
  genres: string[] = [],
  format: string = 'TV'
): string {
  const formatLabel = format === 'MOVIE' ? 'полнометражного аниме-фильма' : 'аниме-сериала';
  if (!genres || genres.length === 0) {
    return `Смотрите все серии ${formatLabel} «${title}» онлайн в высоком качестве Full HD с русской озвучкой и субтитрами.`;
  }
  const translatedGenres = genres
    .map((g) => GENRE_RU_MAP[g] || g)
    .slice(0, 3)
    .join(', ');
  return `Захватывающая история в жанре ${translatedGenres}. Смотрите все серии ${formatLabel} «${title}» онлайн в высоком качестве Full HD с русской озвучкой и субтитрами.`;
}
