export function getKnownRussianTitle(idOrSlug: string | number): string | null {
  const fromDb = lookupRussianAnimeTitle(idOrSlug);
  if (fromDb && /[а-яё]/i.test(fromDb)) return fromDb;

  const key = String(idOrSlug).toLowerCase().trim();
  if (KNOWN_RUSSIAN_TITLES[key]) {
    return KNOWN_RUSSIAN_TITLES[key];
  }
  const cleanKey = key.replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
  if (KNOWN_RUSSIAN_TITLES[cleanKey]) {
    return KNOWN_RUSSIAN_TITLES[cleanKey];
  }

  // Prefix/Sub-string match in known titles
  for (const [dictKey, ruTitle] of Object.entries(KNOWN_RUSSIAN_TITLES)) {
    if (dictKey.length > 5 && (cleanKey.includes(dictKey) || dictKey.includes(cleanKey))) {
      return ruTitle;
    }
  }

  return null;
}

